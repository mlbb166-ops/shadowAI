CREATE OR REPLACE FUNCTION nutrishield_check_child_owner() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.child_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM child_profiles WHERE id=NEW.child_id AND user_id=NEW.user_id) THEN
    RAISE EXCEPTION 'child ownership mismatch';
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS consents_child_owner ON consents;
CREATE TRIGGER consents_child_owner BEFORE INSERT OR UPDATE ON consents FOR EACH ROW EXECUTE FUNCTION nutrishield_check_child_owner();
DROP TRIGGER IF EXISTS jobs_child_owner ON agent_jobs;
CREATE TRIGGER jobs_child_owner BEFORE INSERT OR UPDATE ON agent_jobs FOR EACH ROW EXECUTE FUNCTION nutrishield_check_child_owner();
DROP TRIGGER IF EXISTS runs_child_owner ON agent_runs;
CREATE TRIGGER runs_child_owner BEFORE INSERT OR UPDATE ON agent_runs FOR EACH ROW EXECUTE FUNCTION nutrishield_check_child_owner();

