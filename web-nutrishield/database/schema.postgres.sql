CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL CHECK(length(display_name) BETWEEN 1 AND 120),
    password_salt BYTEA NOT NULL CHECK(length(password_salt) >= 16),
    password_hash BYTEA NOT NULL CHECK(length(password_hash) = 32),
    password_iterations BIGINT NOT NULL CHECK(password_iterations >= 210000),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    disabled_at TEXT
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash BYTEA PRIMARY KEY CHECK(length(token_hash) = 32),
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    last_seen_at TEXT NOT NULL,
    user_agent TEXT,
    ip_hint TEXT,
    revoked_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_user_expiry ON sessions(user_id, expires_at);

CREATE TABLE IF NOT EXISTS child_profiles (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 120),
    birth_date TEXT,
    sex TEXT CHECK(sex IS NULL OR sex IN ('female','male','unspecified')),
    allergies TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_children_user ON child_profiles(user_id, created_at);

CREATE TABLE IF NOT EXISTS consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    child_id TEXT REFERENCES child_profiles(id) ON DELETE CASCADE,
    consent_type TEXT NOT NULL CHECK(consent_type IN ('data_processing','telegram_delivery','agent_assistance')),
    granted BIGINT NOT NULL CHECK(granted IN (0,1)),
    granted_at TEXT,
    revoked_at TEXT,
    created_at TEXT NOT NULL,
    UNIQUE(user_id, child_id, consent_type)
);

CREATE TABLE IF NOT EXISTS channel_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    active_child_id TEXT REFERENCES child_profiles(id) ON DELETE SET NULL,
    provider TEXT NOT NULL CHECK(provider IN ('telegram')),
    provider_user_id TEXT NOT NULL,
    provider_chat_id TEXT NOT NULL,
    display_name TEXT,
    linked_at TEXT NOT NULL,
    unlinked_at TEXT,
    UNIQUE(provider, provider_user_id),
    UNIQUE(provider, provider_chat_id)
);

CREATE TABLE IF NOT EXISTS channel_link_codes (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    child_id TEXT REFERENCES child_profiles(id) ON DELETE CASCADE,
    code_hash BYTEA NOT NULL UNIQUE CHECK(length(code_hash) = 32),
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    consumed_at TEXT,
    consumed_by_identity_id BIGINT REFERENCES channel_identities(id),
    attempt_count BIGINT NOT NULL DEFAULT 0 CHECK(attempt_count >= 0)
);
CREATE INDEX IF NOT EXISTS idx_link_codes_user_expiry ON channel_link_codes(user_id, expires_at);

CREATE TABLE IF NOT EXISTS measurements (
    id TEXT PRIMARY KEY,
    child_id TEXT NOT NULL REFERENCES child_profiles(id) ON DELETE CASCADE,
    measured_at TEXT NOT NULL,
    weight_kg DOUBLE PRECISION CHECK(weight_kg IS NULL OR (weight_kg > 0 AND weight_kg <= 300)),
    height_cm DOUBLE PRECISION CHECK(height_cm IS NULL OR (height_cm > 0 AND height_cm <= 250)),
    head_circumference_cm DOUBLE PRECISION CHECK(head_circumference_cm IS NULL OR (head_circumference_cm > 0 AND head_circumference_cm <= 100)),
    source TEXT NOT NULL DEFAULT 'manual' CHECK(source IN ('manual','telegram','import')),
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    CHECK(weight_kg IS NOT NULL OR height_cm IS NOT NULL OR head_circumference_cm IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_measurements_child_time ON measurements(child_id, measured_at DESC);

CREATE TABLE IF NOT EXISTS daily_logs (
    id TEXT PRIMARY KEY,
    child_id TEXT NOT NULL REFERENCES child_profiles(id) ON DELETE CASCADE,
    log_date TEXT NOT NULL,
    category TEXT NOT NULL CHECK(category IN ('meal','symptom','activity','sleep','note')),
    content TEXT NOT NULL,
    metadata_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL,
    UNIQUE(child_id, log_date, category, content)
);

CREATE TABLE IF NOT EXISTS food_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key TEXT NOT NULL UNIQUE,
