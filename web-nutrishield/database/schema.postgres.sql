CREATE TABLE IF NOT EXISTS canonical_foods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_key TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    normalized_name TEXT NOT NULL,
    brand TEXT,
    barcode TEXT,
    bpom_number TEXT,
